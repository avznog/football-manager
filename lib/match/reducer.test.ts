describe("contracts", () => {
  it("accepts a row exactly as the database returns it", () => {
    // Compiles only if `MatchEvent` satisfies `MatchEventRecord` — including `occurredAt` as a Date.
    const asRecord = (row: MatchEvent): MatchEventRecord => row;
    expect(typeof asRecord).toBe("function");
  });

  it("accepts a log that crossed the RSC boundary as JSON", () => {
    const plain: MatchEventRecord[] = [
      {
        id: "e1",
        type: "KICKOFF",
        period: 1,
        minute: 0,
        clockMs: 0,
        occurredAt: "2026-04-11T08:00:00.000Z",
      },
      {
        id: "e2",
        type: "GOAL_FOR",
        period: 1,
        minute: 11,
        clockMs: 660_000,
        occurredAt: new Date(T0 + 11 * MIN).toISOString(),
        payload: { scorerId: "julien" },
      },
    ];
    const state = reduceMatch(plain, [], CONFIG);
    expect(state.goalsFor).toBe(1);
    expect(state.clock.anchoredAtMs).toBe(T0 + 11 * MIN);
  });

  it("never mutates the log it is given", () => {
    const events = log([
      { type: "KICKOFF", min: 0, period: 1 },
      { type: "GOAL_FOR", min: 11, payload: { scorerId: "julien" } },
    ]);
    const snapshot = JSON.stringify(events);
    reduceMatch(events.reverse(), [], CONFIG);
    expect(JSON.stringify([...events].reverse())).toBe(snapshot);
  });

  it("is deterministic: the same log reduces to the same state, twice", () => {
    expect(reduceMatch(SEED_LOG, [], CONFIG)).toEqual(reduceMatch(SEED_LOG, [], CONFIG));
  });

  it("falls back to 2×30 when the match configuration is missing", () => {
    const state = reduceMatch(SEED_LOG, [], { slots: SLOTS, periodsCount: null, periodMinutes: null });
    expect(state.periods).toEqual({ periodsCount: 2, periodMinutes: 30 });
  });
});
