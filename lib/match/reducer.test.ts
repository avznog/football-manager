describe("an empty log", () => {
  const state = reduceMatch([]);

  it("is a 0-0 that has not started, with no result", () => {
    expect(state.goalsFor).toBe(0);
    expect(state.goalsAgainst).toBe(0);
    expect(state.scoreLabel).toBe("0 – 0");
    expect(state.phase).toBe("before-kickoff");
    expect(state.started).toBe(false);
    expect(state.finished).toBe(false);
    // A match in progress has no result, and neither has one that never began.
    expect(state.result).toBeNull();
  });

  it("knows nothing about anybody and complains about nothing", () => {
    expect(state.players).toEqual([]);
    expect(state.onPitch).toEqual([]);
    expect(state.timeline).toEqual([]);
    expect(state.goalkeeperId).toBeNull();
    expect(state.anomalies).toEqual([]);
  });

  it("still reports the configured periods and a readable clock", () => {
    expect(state.periods).toEqual({ periodsCount: 2, periodMinutes: 30 });
    expect(state.reading.clock).toBe("00:00");
    expect(state.reading.label).toBe("0’");
  });

  it("lists the whole squad on the bench when it is given one", () => {
    const withSquad = reduceMatch([], [], CONFIG);
    expect(withSquad.players).toHaveLength(SQUAD.length);
    expect(withSquad.players.every((player) => player.minutes === 0)).toBe(true);
    expect(withSquad.players.every((player) => player.playedMatch === false)).toBe(true);
    // Supporters are in the squad but are not on the bench: they are not going to play.
    expect(withSquad.bench).toHaveLength(SQUAD.length - 1);
    expect(withSquad.bench).not.toContain("gerard");
  });
});

