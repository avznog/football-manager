describe("the seeded match, reduced", () => {
  const state = reduceMatch(SEED_LOG, [], CONFIG);

  it("finishes 3-2, a win", () => {
    // 11′ Julien, 28′ Karim, 44′ penalty Julien — the 27′ goal was annulled.
    expect(state.goalsFor).toBe(3);
    // 24′ conceded, 51′ own goal by Nico.
    expect(state.goalsAgainst).toBe(2);
    expect(state.scoreLabel).toBe("3 – 2");
    expect(state.result).toBe("win");
    expect(state.finished).toBe(true);
    expect(state.phase).toBe("finished");
    expect(state.periodsStarted).toBe(2);
  });

  it("has nothing to complain about", () => {
    // In particular, Karim taking the striker's slot at 55′ while Julien is still standing in it is
    // not an anomaly: a position change never displaces anybody (rule 6).
    expect(state.anomalies).toEqual([]);
  });

  it("gives every player the minutes he actually played", () => {
    expect(minutesOf(state)).toEqual({
      hugo: 60,
      samir: 60,
      thomas: 60,
      nico: 60,
      karim: 60,
      julien: 55,
      leo: 38,
      yanis: 22,
      momo: 5,
      ali: 0,
      fabien: 0,
      gerard: 0,
    });
  });

  it("credits goals, assists, own goals, penalties and fouls to the right players", () => {
    const julien = playerState(state, "julien")!;
    // A scored penalty is a goal *and* a penalty: the two fields must never be added together.
    expect(julien).toMatchObject({ goals: 2, penaltiesScored: 1, assists: 0 });
    expect(playerState(state, "karim")).toMatchObject({ goals: 1, assists: 1 });
    // Léo's only goal was annulled; his assist at 28′ stands.
    expect(playerState(state, "leo")).toMatchObject({ goals: 0, assists: 1 });
    expect(playerState(state, "nico")).toMatchObject({ ownGoals: 1, goals: 0 });
    expect(playerState(state, "momo")).toMatchObject({ penaltiesMissed: 1, goals: 0 });
    expect(playerState(state, "thomas")).toMatchObject({ fouls: 1 });

    const scored = state.players.reduce((total, player) => total + player.goals, 0);
    expect(scored).toBe(state.goalsFor);
  });

  it("counts clean minutes per spell, so a substitute's fresh start is not wasted", () => {
    // Everybody who started was on when we conceded at 24′: 24 clean minutes each, no more.
    expect(playerState(state, "samir")!.cleanMinutes).toBe(24);
    expect(playerState(state, "julien")!.cleanMinutes).toBe(24);
    // Yanis came on at 38′ with the sheet already broken, and kept his own until the own goal at 51′.
    expect(playerState(state, "yanis")!.cleanMinutes).toBe(13);
    // Momo came on at 55′ and conceded nothing at all.
    expect(playerState(state, "momo")).toMatchObject({ cleanMinutes: 5, concededWhileOn: 0 });
  });

  it("counts goals conceded while each player was on the pitch", () => {
    expect(playerState(state, "hugo")!.concededWhileOn).toBe(2);
    // Léo went off at 38′, so the own goal at 51′ is not on his record.
    expect(playerState(state, "leo")!.concededWhileOn).toBe(1);
    expect(playerState(state, "yanis")!.concededWhileOn).toBe(1);
  });

  it("knows who was in goal, and for how long he kept it clean", () => {
    expect(state.goalkeeperId).toBe("hugo");
    expect(playerState(state, "hugo")).toMatchObject({
      wasGoalkeeper: true,
      gkMinutes: 60,
      gkCleanMinutes: 24,
      concededWhileGk: 2,
    });
    expect(playerState(state, "samir")!.wasGoalkeeper).toBe(false);
    expect(playerState(state, "samir")!.gkMinutes).toBe(0);
  });

  it("follows each player's position over time", () => {
    const karim = playerState(state, "karim")!;
    expect(karim.positionSpells).toEqual([
      { slotId: SLOT.mc2, positionCode: "MC", fromClockMs: 0, toClockMs: 55 * MIN },
      { slotId: SLOT.at, positionCode: "AT", fromClockMs: 55 * MIN, toClockMs: null },
    ]);
    expect(karim.positionCode).toBe("AT");
    // Momo took the slot Karim vacated, which is what the substitution payload says.
    expect(playerState(state, "momo")!.positionCode).toBe("MC");
  });

  it("records a spell for a player who came on and went off again", () => {
    expect(playerState(state, "leo")!.spells).toEqual([{ fromClockMs: 0, toClockMs: 38 * MIN }]);
    expect(playerState(state, "yanis")!.spells).toEqual([
      { fromClockMs: 38 * MIN, toClockMs: null },
    ]);
    expect(playerState(state, "leo")!.onPitch).toBe(false);
    expect(playerState(state, "yanis")!.onPitch).toBe(true);
  });

  it("separates the eleven who started from those who came on", () => {
    const started = state.players.filter((player) => player.startedMatch).map((p) => p.memberId);
    expect(started.sort()).toEqual(["hugo", "julien", "karim", "leo", "nico", "samir", "thomas"]);
    expect(playerState(state, "momo")!.startedMatch).toBe(false);
    expect(playerState(state, "ali")!.playedMatch).toBe(false);
  });

  it("does not take anybody off at the final whistle — the state shows who finished the match", () => {
    expect(state.onPitch).toHaveLength(7);
    expect(state.onPitch.map((entry) => entry.memberId)).toEqual([
      "hugo",
      "samir",
      "thomas",
      "nico",
      "yanis",
      "momo",
      "karim",
    ]);
    expect(state.onPitch[0]).toMatchObject({ isGoalkeeper: true, sinceClockMs: 60 * MIN });
    expect([...state.bench].sort()).toEqual(["ali", "fabien", "leo", "julien"].sort());
  });

  it("keeps every event in the timeline, including the annulled goal and its annulment", () => {
    expect(state.timeline).toHaveLength(SEED_LOG.length);
    const annulled = state.timeline.find((entry) => entry.eventId === "e6")!;
    expect(annulled).toMatchObject({
      type: "GOAL_FOR",
      voided: true,
      voidedByEventId: "e7",
      minuteLabel: "27’",
      labelFr: "But",
      // It changed nothing, so it carries no score.
      scoreAfter: null,
    });
    const annulment = state.timeline.find((entry) => entry.eventId === "e7")!;
    expect(annulment).toMatchObject({ type: "VOID", voidsEventId: "e6", labelFr: "Annulation" });
    expect(state.voidedEventIds).toEqual(["e6"]);
  });

  it("carries the running score on the events that changed it", () => {
    const scores = state.timeline
      .filter((entry) => entry.scoreAfter !== null)
      .map((entry) => `${entry.minuteLabel} ${entry.scoreAfter!.goalsFor}-${entry.scoreAfter!.goalsAgainst}`);
    expect(scores).toEqual(["11’ 1-0", "24’ 1-1", "28’ 2-1", "44’ 3-1", "51’ 3-2"]);
  });

  it("names the players each timeline entry is about, without knowing their names", () => {
    const goal = state.timeline.find((entry) => entry.eventId === "e3")!;
    expect(goal.actors).toEqual([
      { memberId: "julien", role: "scorer" },
      { memberId: "karim", role: "assist" },
    ]);
    const substitution = state.timeline.find((entry) => entry.eventId === "e11")!;
    expect(substitution.actors).toEqual([
      { memberId: "leo", role: "out" },
      { memberId: "yanis", role: "in" },
    ]);
    const initial = state.timeline.find((entry) => entry.eventId === "e2")!;
    expect(initial.actors).toHaveLength(7);
    expect(initial.actors.every((actor) => actor.role === "in")).toBe(true);
  });

  it("notes when the goals went in", () => {
    expect(state.scoredAt).toEqual([11 * MIN, 28 * MIN, 44 * MIN]);
    expect(state.concededAt).toEqual([24 * MIN, 51 * MIN]);
  });

  it("records which planned composition was applied", () => {
    expect(state.appliedLineupIds).toEqual(["l-initial"]);
  });

  it("reduces the same log to the same state whatever order the rows arrive in", () => {
    // The outbox retries, so insertion order is meaningless: an event logged at 12′ can land after
    // one logged at 40′.
    const shuffled = [
      SEED_LOG[14],
      SEED_LOG[3],
      SEED_LOG[17],
      SEED_LOG[1],
      SEED_LOG[8],
      SEED_LOG[6],
      SEED_LOG[13],
      SEED_LOG[0],
      SEED_LOG[11],
      SEED_LOG[5],
      SEED_LOG[16],
      SEED_LOG[2],
      SEED_LOG[9],
      SEED_LOG[15],
      SEED_LOG[4],
      SEED_LOG[12],
      SEED_LOG[7],
      SEED_LOG[10],
    ];
    expect(shuffled).toHaveLength(SEED_LOG.length);
    expect(reduceMatch(shuffled, [], CONFIG)).toEqual(state);
  });

  it("maps onto the match_player_stats cache", () => {
    const rows = toMatchPlayerStats(state);
    expect(rows).toHaveLength(SQUAD.length);
    expect(rows.find((row) => row.teamMemberId === "julien")).toEqual({
      teamMemberId: "julien",
      minutes: 55,
      goals: 2,
      assists: 0,
      ownGoals: 0,
      penaltiesScored: 1,
      penaltiesMissed: 0,
      fouls: 0,
      gkMinutes: 0,
      cleanMinutes: 24,
      concededWhileOn: 2,
      gkCleanMinutes: 0,
      concededWhileGk: 0,
      squadRole: "starter",
    });
    // The keeper's two figures are the ones decision 018 added a column for: they are not
    // derivable from the field-player pair above, and this is the row that proves it.
    expect(rows.find((row) => row.teamMemberId === "hugo")).toMatchObject({
      gkMinutes: 60,
      gkCleanMinutes: 24,
      concededWhileGk: 2,
    });
  });

  it("can hand the timeline back newest first, as game mode shows it", () => {
    expect(reverseTimeline(state)[0].type).toBe("FINAL_WHISTLE");
  });
});

