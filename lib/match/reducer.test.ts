describe("minutes played", () => {
  it("excludes half-time, so 20′ to 40′ is twenty minutes and not the length of the break", () => {
    const state = reduceMatch(
      log([
        { type: "KICKOFF", min: 0, period: 1 },
        { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload({ [SLOT.gb]: "hugo", [SLOT.mc1]: "leo" }) },
        { type: "SUBSTITUTION", min: 20, payload: { outId: "leo", inId: "yanis", slotId: SLOT.mc1 } },
        { type: "PERIOD_END", min: 30, period: 1 },
        { type: "KICKOFF", min: 30, period: 2 },
        { type: "SUBSTITUTION", min: 40, payload: { outId: "yanis", inId: "leo", slotId: SLOT.mc1 } },
        { type: "PERIOD_END", min: 60, period: 2 },
        { type: "FINAL_WHISTLE", min: 60, period: 2 },
      ]),
      [],
      { slots: SLOTS },
    );
    expect(playerState(state, "yanis")!.minutes).toBe(20);
    // Léo has two spells: 0′→20′ and 40′→60′.
    expect(playerState(state, "leo")!.minutes).toBe(40);
    expect(playerState(state, "leo")!.spells).toEqual([
      { fromClockMs: 0, toClockMs: 20 * MIN },
      { fromClockMs: 40 * MIN, toClockMs: null },
    ]);
  });

  it("accrues nothing across a break or after the final whistle", () => {
    const state = reduceMatch(
      log([
        { type: "KICKOFF", min: 0, period: 1 },
        { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload({ [SLOT.gb]: "hugo" }) },
        { type: "PERIOD_END", min: 30, period: 1 },
        // No second kick-off: the log stops at half-time.
        { type: "FOUL", min: 30, period: 1, payload: { memberId: "hugo" } },
      ]),
      [],
      { slots: SLOTS },
    );
    expect(playerState(state, "hugo")!.minutes).toBe(30);
    expect(state.phase).toBe("break");
    expect(state.finished).toBe(false);
  });

  it("rounds to whole minutes rather than rounding every appearance up", () => {
    const state = reduceMatch(
      log([
        { type: "KICKOFF", min: 0, period: 1 },
        { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload({ [SLOT.at]: "julien" }) },
        { type: "SUBSTITUTION", min: 58, payload: { outId: "julien", inId: "momo", slotId: SLOT.at } },
        { type: "FINAL_WHISTLE", min: 60, period: 2 },
      ]),
      [],
      { slots: SLOTS },
    );
    // Two minutes and no more: broadcast football would say three, and a season of those would
    // inflate a bench player's total by a third.
    expect(playerState(state, "momo")).toMatchObject({ playedMs: 2 * MIN, minutes: 2 });
  });

  it("handles three periods, with the clock running straight through", () => {
    const threeTwenty = { periodsCount: 3, periodMinutes: 20 };
    const state = reduceMatch(
      log(
        [
          { type: "KICKOFF", min: 0, period: 1 },
          { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload({ [SLOT.gb]: "hugo", [SLOT.at]: "julien" }) },
          { type: "PERIOD_END", min: 20, period: 1 },
          { type: "KICKOFF", min: 20, period: 2 },
          { type: "GOAL_FOR", min: 25, payload: { scorerId: "julien" } },
          { type: "PERIOD_END", min: 40, period: 2 },
          { type: "KICKOFF", min: 40, period: 3 },
          { type: "SUBSTITUTION", min: 50, payload: { outId: "julien", inId: "momo", slotId: SLOT.at } },
          { type: "PERIOD_END", min: 60, period: 3 },
          { type: "FINAL_WHISTLE", min: 60, period: 3 },
        ],
        threeTwenty,
      ),
      [],
      { ...CONFIG, ...threeTwenty },
    );
    expect(state.periods).toEqual(threeTwenty);
    expect(state.periodsStarted).toBe(3);
    expect(playerState(state, "hugo")!.minutes).toBe(60);
    expect(playerState(state, "julien")!.minutes).toBe(50);
    expect(playerState(state, "momo")!.minutes).toBe(10);
    // Continuous minutes: the third period runs 40′→60′, and the goal in the second reads 25′.
    expect(state.timeline.find((entry) => entry.type === "GOAL_FOR")!.minuteLabel).toBe("25’");
  });
});

