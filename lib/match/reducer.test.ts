describe("a match in progress", () => {
  const liveLog = log([
    { type: "KICKOFF", min: 0, period: 1 },
    { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload(STARTING_ELEVEN) },
    { type: "GOAL_FOR", min: 11, payload: { scorerId: "julien" } },
  ]);

  it("runs the clock and the minutes up to now", () => {
    const state = reduceMatch(liveLog, [], { ...CONFIG, nowMs: T0 + 24 * MIN });
    expect(state.phase).toBe("running");
    expect(state.reading.minute).toBe(24);
    expect(state.reading.running).toBe(true);
    expect(state.finished).toBe(false);
    // A match in progress has no result, whatever the score.
    expect(state.result).toBeNull();
    expect(playerState(state, "hugo")!.minutes).toBe(24);
    expect(playerState(state, "hugo")!.cleanMinutes).toBe(24);
  });

  it("stops at the last event when no wall clock is supplied", () => {
    // A server render with no clock is not allowed to invent minutes.
    const state = reduceMatch(liveLog, [], CONFIG);
    expect(state.reading.minute).toBe(11);
    expect(playerState(state, "hugo")!.minutes).toBe(11);
  });

  it("freezes everything while the clock is paused", () => {
    const paused = log([
      { type: "KICKOFF", min: 0, period: 1 },
      { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload(STARTING_ELEVEN) },
      { type: "PAUSE", min: 10, payload: { reason: "joueur au sol" } },
    ]);
    const state = reduceMatch(paused, [], { ...CONFIG, nowMs: T0 + 25 * MIN });
    expect(state.phase).toBe("paused");
    expect(state.reading.minute).toBe(10);
    // Fifteen minutes of wall clock have passed and nobody has played a second of them.
    expect(playerState(state, "hugo")!.minutes).toBe(10);
  });

  it("resumes where it stopped: a pause consumes no match time", () => {
    const resumed = log([
      { type: "KICKOFF", min: 0, period: 1 },
      { type: "LINEUP_APPLIED", min: 0, period: 1, payload: lineupPayload(STARTING_ELEVEN) },
      { type: "PAUSE", min: 10 },
      { type: "RESUME", min: 10 },
      { type: "PERIOD_END", min: 30, period: 1 },
      { type: "FINAL_WHISTLE", min: 30, period: 1 },
    ]);
    const state = reduceMatch(resumed, [], CONFIG);
    expect(playerState(state, "hugo")!.minutes).toBe(30);
    expect(state.playIntervals).toEqual([
      { period: 1, startMs: 0, endMs: 10 * MIN },
      { period: 1, startMs: 10 * MIN, endMs: 30 * MIN },
    ]);
    expect(state.anomalies).toEqual([]);
  });

  it("is between periods at half-time, and waiting for a whistle after the last one", () => {
    const halfTime = log([
      { type: "KICKOFF", min: 0, period: 1 },
      { type: "PERIOD_END", min: 30, period: 1 },
    ]);
    expect(reduceMatch(halfTime, [], CONFIG).phase).toBe("break");
    expect(reduceMatch(halfTime, [], CONFIG).reading.awaitingFinalWhistle).toBe(false);

    const fullTime = log([
      { type: "KICKOFF", min: 0, period: 1 },
      { type: "PERIOD_END", min: 30, period: 1 },
      { type: "KICKOFF", min: 30, period: 2 },
      { type: "PERIOD_END", min: 60, period: 2 },
    ]);
    expect(reduceMatch(fullTime, [], CONFIG).reading.awaitingFinalWhistle).toBe(true);
  });
});

